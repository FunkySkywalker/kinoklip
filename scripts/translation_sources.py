"""translation_sources.py --write | --check: keep the texts that lupdate cannot see in the .ts files.

Many source files translate through a small helper instead of tr():

    QString tr(const char* text) { return QCoreApplication::translate("kk::Mask", text); }

lupdate only reads translate() calls whose second argument is a string literal, so every
`tr("...")` through such a helper never reached the .ts files (the text stayed English). This
script finds the helpers (any function whose body forwards a parameter to
QCoreApplication::translate("<context>", <parameter>), also through one more wrapper such as
`Node A(const char* id, const char* label) { ... T(label) ... }`), collects the string literals of
all its calls in the same file and writes them as plain translate() calls to
resources/translations/helper_strings.cpp. That file is not compiled: the update_translations
target hands it to lupdate next to src/, so the texts get into the .ts files under the context used
at run time.

  --write   regenerate resources/translations/helper_strings.cpp (update_translations does it)
  --check   fail if that file is out of date, if a helper text is missing or unfinished in a .ts
            file, or if any .ts entry is unfinished (ctest: check_translations)
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "resources/translations/helper_strings.cpp"
HEADER = (
    "// Generated by scripts/translation_sources.py --write: the texts of the translate() helpers\n"
    "// that lupdate cannot follow. Not compiled; update_translations passes it to lupdate.\n"
)

ESC = {"n": "\n", "t": "\t", "r": "\r", '"': '"', "'": "'", "\\": "\\", "0": "\0"}


def mask(src):
    """The source with comments blanked out (strings and char literals kept, newlines kept)."""
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        if src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
        elif src.startswith("/*", i):
            j = src.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append(re.sub(r"[^\n]", " ", src[i:j]))
            i = j
        elif c in "\"'":
            j = i + 1
            while j < n and src[j] != c:
                j += 2 if src[j] == "\\" else 1
            out.append(src[i : j + 1])
            i = j + 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


def split_args(text, start):
    """Arguments of the call whose '(' is at text[start]; returns (list of strings, end index)."""
    args, depth, cur, i, n = [], 0, [], start, len(text)
    while i < n:
        c = text[i]
        if c in "\"'":
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == "\\" else 1
            cur.append(text[i : j + 1])
            i = j + 1
            continue
        if c in "([{":
            depth += 1
            if depth > 1:
                cur.append(c)
        elif c in ")]}":
            depth -= 1
            if depth == 0:
                args.append("".join(cur))
                return args, i
            cur.append(c)
        elif c == "," and depth == 1:
            args.append("".join(cur))
            cur = []
        else:
            cur.append(c)
        i += 1
    return args, n


LITERAL = re.compile(r'"(?:[^"\\]|\\.)*"(?:\s*"(?:[^"\\]|\\.)*")*')
PIECE = re.compile(r'"((?:[^"\\]|\\.)*)"')


def literals(arg):
    """The string literals in one argument (adjacent ones joined): source form, no quotes."""
    if "NOOP" in arg:  # QT_TRANSLATE_NOOP(...) / QT_TR_NOOP(...): lupdate reads those itself
        return []
    return ["".join(PIECE.findall(m.group(0))) for m in LITERAL.finditer(arg)]


def decode(s):
    return re.sub(r"\\(.)", lambda m: ESC.get(m.group(1), m.group(1)), s)


IDENT = r"[A-Za-z_]\w*"
DEF = re.compile(r"(?:^|[\s:*&>])(" + IDENT + r")\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)\s*(?:const\s*)?\{")
LAMBDA = re.compile(r"\bauto\s+(" + IDENT + r")\s*=\s*\[[^\]]*\]\s*\(([^()]*)\)\s*(?:->\s*\w+\s*)?\{")
TRANSLATE = re.compile(r'QCoreApplication::translate\(\s*"([^"]+)"\s*,\s*(' + IDENT + r")\b")


def block_end(text, brace):
    depth, i, n = 0, brace, len(text)
    while i < n:
        c = text[i]
        if c in "\"'":
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == "\\" else 1
            i = j
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return n


def params(plist):
    return [p.strip() for p in plist.split(",")]


def param_name(p):
    m = re.search(r"(" + IDENT + r")\s*(?:=.*)?$", p)
    return m.group(1) if m else ""


def scope_end(text, pos):
    """End of the block that contains pos (namespace or function body): the unmatched '}'."""
    depth, i, n = 0, pos, len(text)
    while i < n:
        c = text[i]
        if c in "\"'":
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == "\\" else 1
            i = j
        elif c == "{":
            depth += 1
        elif c == "}":
            if depth == 0:
                return i
            depth -= 1
        i += 1
    return n


GLUED = []


def scan(path):
    """-> (entries {(context, text, comment): numerus}, warnings) for one source file."""
    text = mask(path.read_text(encoding="utf-8"))
    found, warn = {}, []
    glued = GLUED
    # helpers: (name, context, arg index of the text, start of scope, end of scope)
    helpers = []
    for rx in (DEF, LAMBDA):
        for m in rx.finditer(text):
            body_start = m.end() - 1
            body = text[body_start : block_end(text, body_start) + 1]
            plist = params(m.group(2))
            for tm in TRANSLATE.finditer(body):
                names = [param_name(p) for p in plist]
                if tm.group(2) in names:
                    helpers.append([m.group(1), tm.group(1), names.index(tm.group(2)), m.start(),
                                    scope_end(text, m.start()) if rx is LAMBDA else len(text), plist])
    # wrappers around a helper: functions that pass one of their own parameters to it
    changed = True
    while changed:
        changed = False
        for m in DEF.finditer(text):
            body_start = m.end() - 1
            body = text[body_start : block_end(text, body_start) + 1]
            names = [param_name(p) for p in params(m.group(2))]
            for h in list(helpers):
                for cm in re.finditer(r"(?<![\w.>:])" + re.escape(h[0]) + r"\(", body):
                    args, _ = split_args(body, cm.end() - 1)
                    idx = h[2]
                    if idx < len(args) and args[idx].strip() in names:
                        w = [m.group(1), h[1], names.index(args[idx].strip()), m.start(), h[4], params(m.group(2))]
                        if not any(x[:3] == w[:3] and x[3] == w[3] for x in helpers) and m.group(1) != h[0]:
                            helpers.append(w)
                            changed = True
    names_seen = {h[0] for h in helpers}
    for name in names_seen:
        for cm in re.finditer(r"(?<![\w.>:])" + re.escape(name) + r"\(", text):
            # the innermost helper of this name whose scope holds the call
            cands = [h for h in helpers if h[0] == name and h[3] <= cm.start() <= h[4]]
            if not cands:
                continue
            _, ctx, idx, _, _, plist = max(cands, key=lambda h: h[3])
            open_at = cm.end() - 1
            # the definition itself, or a declaration: skip
            if re.match(r"[^()]*\bconst\s+char\s*\*", text[open_at + 1 : open_at + 60]):
                continue
            args, _ = split_args(text, open_at)
            if idx >= len(args):
                continue
            lits = literals(args[idx])
            if lits and re.search(r'\x00\s*[A-Za-z_]|[A-Za-z_]\w*\s*\x00', LITERAL.sub('\x00', args[idx])):
                glued.append(f"{path.relative_to(ROOT)}: {name}({args[idx].strip()[:50]}) joins a literal and a macro")
                continue
            line = text.count("\n", 0, cm.start()) + 1
            if not lits:
                if args[idx].strip() and "NOOP" not in args[idx]:
                    warn.append(f"{path.relative_to(ROOT)}:{line}: {name}({args[idx].strip()[:40]}) is not a literal")
                continue
            comment = ""
            # a second literal argument of a tr(text, disambiguation, n) helper is the comment
            if len(plist) >= 2 and "disambiguation" in plist[1] and len(args) > 1:
                cl = literals(args[1])
                comment = cl[0] if cl else ""
            # numerus only when the call passes the count (say("...", n)), not for the singular /
            # plural pairs that plural() picks between
            pnames = [param_name(p) for p in plist]
            counted = "n" in pnames and len(args) > pnames.index("n")
            for lit in lits:
                found[(ctx, lit, comment)] = counted and "%n" in lit
    return found, warn


def collect():
    entries, warns = {}, []
    for p in sorted((ROOT / "src").rglob("*")):
        if p.suffix not in (".cpp", ".h") or not p.is_file():
            continue
        if "translate(" not in p.read_text(encoding="utf-8"):
            continue
        f, w = scan(p)
        entries.update(f)
        warns += w
    return entries, warns


def render(entries):
    lines = [HEADER]
    for (ctx, lit, comment), numerus in sorted(entries.items()):
        tail = f', "{comment}"' if comment else (", nullptr" if numerus else "")
        tail += ", 1" if numerus else ""
        lines.append(f'QCoreApplication::translate("{ctx}", "{lit}"{tail});\n')
    return "".join(lines)


def ts_messages(ts):
    """{(context, source, comment): translation state} of one .ts file."""
    out = {}
    for ctx in ET.parse(ts).getroot().findall("context"):
        name = ctx.findtext("name")
        for msg in ctx.findall("message"):
            tr = msg.find("translation")
            ok = tr is not None and tr.get("type") not in ("unfinished", "vanished", "obsolete")
            if ok:
                forms = tr.findall("numerusform")
                ok = all((f.text or "") for f in forms) if forms else bool(tr.text)
            out[(name, msg.findtext("source") or "", msg.findtext("comment") or "")] = ok
    return out


def check(entries):
    problems = list(GLUED)
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != render(entries):
        problems.append(
            f"{OUT.relative_to(ROOT)} is out of date: run scripts/translation_sources.py --write "
            "(or the update_translations target) and translate the new texts"
        )
    for ts in sorted((ROOT / "resources/translations").glob("*.ts")):
        msgs = ts_messages(ts)
        for key, ok in msgs.items():
            if not ok:
                problems.append(f"{ts.name}: unfinished: [{key[0]}] {key[1][:60]}")
        for (ctx, lit, comment) in entries:
            key = (ctx, decode(lit), decode(comment))
            if key not in msgs:
                problems.append(f"{ts.name}: missing: [{ctx}] {decode(lit)[:60]}")
    return problems


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    entries, warns = collect()
    if "-v" in sys.argv or mode == "--write":
        for w in warns:
            print("note:", w, file=sys.stderr)
    if mode == "--write":
        OUT.write_text(render(entries), encoding="utf-8")
        print(f"{OUT.relative_to(ROOT)}: {len(entries)} texts")
        return 0
    problems = check(entries)
    for p in problems[:60]:
        print(p)
    if len(problems) > 60:
        print(f"... and {len(problems) - 60} more")
    print("check_translations:", "FAILED" if problems else "ok", f"({len(entries)} helper texts)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
